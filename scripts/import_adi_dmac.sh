#!/usr/bin/env bash
# ============================================================================
# import_adi_dmac.sh
#   Copy the axi_dmac sources this project needs out of a pristine ADI HDL
#   checkout, then apply the local patches on top.
#
#   The copied tree under rtl/third_party/ is ADI code, unmodified except for
#   what patches/ applies.  Never edit it by hand - add a patch instead.
#
#   Usage: scripts/import_adi_dmac.sh [path-to-adi-hdl]
# ============================================================================
set -euo pipefail

ADI_HDL="${1:-$HOME/Workspace/adi_hdl}"
REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$REPO_ROOT/rtl/third_party/adi_hdl"

if [ ! -d "$ADI_HDL/library/axi_dmac" ]; then
  echo "ERROR: ADI HDL not found at $ADI_HDL" >&2
  exit 1
fi

AXI_DMAC_FILES=(
  address_generator.v  axi_dmac_burst_memory.v  axi_dmac_ext_sync.v
  axi_dmac_framelock.v axi_dmac_regmap_request.v axi_dmac_regmap.v
  axi_dmac_reset_manager.v axi_dmac_resize_dest.v axi_dmac_resize_src.v
  axi_dmac_response_manager.v axi_dmac_transfer.v axi_dmac.v
  axi_register_slice.v data_mover.v dest_axi_mm.v dest_axi_stream.v
  dest_fifo_inf.v dmac_2d_transfer.v dmac_sg.v inc_id.vh
  request_arb.v request_generator.v response_generator.v response_handler.v
  resp.vh splitter.v src_axi_mm.v src_axi_stream.v src_fifo_inf.v
)
COMMON_FILES=(ad_mem_asym.v ad_mem.v up_axi.v)
FIFO_FILES=(util_axis_fifo_address_generator.v util_axis_fifo.v)
CDC_FILES=(sync_bits.v sync_data.v sync_event.v sync_gray.v)

echo "==> cleaning $DEST"
rm -rf "$DEST"
mkdir -p "$DEST/library"/{axi_dmac,common,util_axis_fifo,util_cdc}

copy_set() {
  local subdir="$1"; shift
  for f in "$@"; do
    cp "$ADI_HDL/library/$subdir/$f" "$DEST/library/$subdir/$f"
  done
  echo "    $subdir : $# files"
}

echo "==> copying RTL"
copy_set axi_dmac        "${AXI_DMAC_FILES[@]}"
copy_set common          "${COMMON_FILES[@]}"
copy_set util_axis_fifo  "${FIFO_FILES[@]}"
copy_set util_cdc        "${CDC_FILES[@]}"

echo "==> copying licenses"
for l in LICENSE LICENSE_ADIBSD LICENSE_ADIJESD204 \
         LICENSE_BSD-1-Clause LICENSE_GPL2 LICENSE_LGPL; do
  [ -f "$ADI_HDL/$l" ] && cp "$ADI_HDL/$l" "$DEST/$l"
done

echo "==> writing provenance"
ADI_SHA="$(git -C "$ADI_HDL" rev-parse HEAD)"
ADI_BRANCH="$(git -C "$ADI_HDL" rev-parse --abbrev-ref HEAD)"
cat > "$DEST/README.md" <<EOF
# Imported ADI HDL sources

Generated by \`scripts/import_adi_dmac.sh\` - **do not edit by hand.**

| item | value |
|---|---|
| upstream | https://github.com/analogdevicesinc/hdl |
| branch | \`$ADI_BRANCH\` |
| commit | \`$ADI_SHA\` |
| imported | $(date -u +%Y-%m-%d) |

Local modifications live in \`patches/\` and are applied by the import script.
To change this code, add a patch - never edit these files directly.
EOF

echo "==> applying patches"
shopt -s nullglob
for p in "$REPO_ROOT"/patches/*.patch; do
  echo "    $(basename "$p")"
  git -C "$REPO_ROOT" apply "$p"
done
shopt -u nullglob

echo "==> done"
find "$DEST/library" -name '*.v' -o -name '*.vh' | wc -l | xargs echo "    RTL files:"